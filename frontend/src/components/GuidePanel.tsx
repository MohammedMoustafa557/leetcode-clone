import { useEffect, useState } from 'react'
import { api } from '../api/client'
import type { Guide } from '../api/types'

export default function GuidePanel({ slug }: { slug: string }) {
  const [guide, setGuide] = useState<Guide | null>(null)
  const [error, setError] = useState('')
  const [shown, setShown] = useState(0)
  const [showAr, setShowAr] = useState(false)
  useEffect(() => {
    setGuide(null); setShown(0)
    api.guide(slug).then(setGuide).catch((e: Error) => setError(e.message))
  }, [slug])
  if (error) return <p className="muted">Guide unavailable: {error}</p>
  if (!guide) return <span className="spinner" />
  return (
    <div className="guide">
      <div className="section-title" style={{ marginTop: 0 }}>Hints</div>
      {guide.hints.slice(0, shown).map((h, i) => <p key={i} className="hint-box"><b>Hint {i + 1}.</b> {h}</p>)}
      {shown < guide.hints.length && <button className="btn" onClick={() => setShown(shown + 1)}>Show hint {shown + 1} of {guide.hints.length}</button>}
      <div className="section-title">Explanation (simple English)</div>
      <p>{guide.explanation}</p>
      <p><b>Time:</b> {guide.time_complexity} · <b>Space:</b> {guide.space_complexity}</p>
      <p className="faint" style={{ fontSize: 12 }}>{guide.complexity_note}</p>
      <div className="section-title">
        Say it in the interview{' '}
        <button className="btn btn-ghost" onClick={() => setShowAr(!showAr)}>{showAr ? 'Hide Arabic' : 'Show Arabic'}</button>
      </div>
      <ol className="sentences">
        {guide.interview_sentences.map((s, i) => (
          <li key={i}>{s.en}{showAr && <div dir="rtl" lang="ar" className="muted">{s.ar}</div>}</li>
        ))}
      </ol>
      <p className="faint" style={{ fontSize: 12 }}>
        {guide.source === 'llm' ? 'Generated by the configured LLM and cached.' : 'Derived automatically from the topic tags and the reference solution (no AI key configured).'}
      </p>
    </div>
  )
}
